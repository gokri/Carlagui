"""Export scenario config as OpenSCENARIO (.xosc) or Python script (.py)."""

import xml.etree.ElementTree as ET
from xml.dom import minidom
import textwrap
import os


# ─────────────────────────────────────────────────────────────────────────────
# OpenSCENARIO 1.0 exporter
# ─────────────────────────────────────────────────────────────────────────────
def export_xosc(config: dict, path: str):
    """
    config keys:
      map_name, ego_blueprint, ego_spawn (x,y,z), ego_dest (x,y,z),
      ego_speed, stop_time, npcs: [{blueprint, spawn(x,y,z), speed}],
      pedestrians: [{spawn(x,y,z), speed}], weather_preset
    """
    root = ET.Element("OpenSCENARIO")

    # FileHeader
    fh = ET.SubElement(root, "FileHeader")
    fh.set("description", "Generated by CARLA GUI")
    fh.set("author", "CarlaGUI")
    fh.set("revMajor", "1"); fh.set("revMinor", "0")

    # ParameterDeclarations
    ET.SubElement(root, "ParameterDeclarations")

    # CatalogLocations
    cl = ET.SubElement(root, "CatalogLocations")
    for name in ("VehicleCatalog", "PedestrianCatalog", "ControllerCatalog",
                 "ManeuverCatalog", "MiscObjectCatalog", "EnvironmentCatalog",
                 "EntityCatalog", "TrajectoryCatalog", "RouteCatalog"):
        ET.SubElement(ET.SubElement(cl, name), "Directory").set("path", "")

    # RoadNetwork
    rn = ET.SubElement(root, "RoadNetwork")
    ET.SubElement(rn, "LogicFile").set("filepath", config.get("map_name", "Town01"))
    ET.SubElement(rn, "SceneGraphFile").set("filepath", "")

    # Entities
    entities = ET.SubElement(root, "Entities")

    def _vehicle_entity(parent, name, blueprint, x, y, z, heading=0.0):
        eo = ET.SubElement(parent, "EntityObject")
        eo.set("name", name)
        ve = ET.SubElement(eo, "Vehicle")
        ve.set("name", blueprint); ve.set("vehicleCategory", "car")
        bb = ET.SubElement(ve, "BoundingBox")
        ET.SubElement(bb, "Center").attrib.update({"x": "1.5", "y": "0", "z": "0.9"})
        ET.SubElement(bb, "Dimensions").attrib.update({"width": "2", "length": "4.5", "height": "1.5"})
        perf = ET.SubElement(ve, "Performance")
        perf.attrib.update({"maxSpeed": "69.44", "maxAcceleration": "10", "maxDeceleration": "10"})
        ax = ET.SubElement(ve, "Axles")
        fa = ET.SubElement(ax, "FrontAxle")
        fa.attrib.update({"maxSteering": "0.5", "wheelDiameter": "0.6",
                          "trackWidth": "1.8", "positionX": "3.1", "positionZ": "0.3"})
        ra = ET.SubElement(ax, "RearAxle")
        ra.attrib.update({"maxSteering": "0", "wheelDiameter": "0.6",
                          "trackWidth": "1.8", "positionX": "0", "positionZ": "0.3"})
        ET.SubElement(ve, "Properties")

    def _pedestrian_entity(parent, name, x, y, z):
        eo = ET.SubElement(parent, "EntityObject")
        eo.set("name", name)
        pe = ET.SubElement(eo, "Pedestrian")
        pe.set("model", "walker.pedestrian.0001")
        pe.set("pedestrianCategory", "pedestrian")
        pe.set("name", name)
        bb = ET.SubElement(pe, "BoundingBox")
        ET.SubElement(bb, "Center").attrib.update({"x": "0", "y": "0", "z": "0.9"})
        ET.SubElement(bb, "Dimensions").attrib.update({"width": "0.5", "length": "0.5", "height": "1.8"})
        ET.SubElement(pe, "Properties")

    ego_sp = config.get("ego_spawn", (0, 0, 0))
    _vehicle_entity(entities, "ego", config.get("ego_blueprint", "vehicle.tesla.model3"),
                    *ego_sp)

    for i, npc in enumerate(config.get("npcs", [])):
        _vehicle_entity(entities, f"npc_{i}", npc.get("blueprint", "vehicle.audi.a2"),
                        *npc.get("spawn", (0, 0, 0)))

    for i, ped in enumerate(config.get("pedestrians", [])):
        _pedestrian_entity(entities, f"pedestrian_{i}", *ped.get("spawn", (0, 0, 0)))

    # Storyboard
    sb = ET.SubElement(root, "Storyboard")
    init = ET.SubElement(sb, "Init")
    actions = ET.SubElement(init, "Actions")

    def _init_action(name, x, y, z, speed=0.0):
        pa = ET.SubElement(actions, "Private")
        pa.set("entityRef", name)
        act = ET.SubElement(pa, "PrivateAction")
        tp = ET.SubElement(act, "TeleportAction")
        pos = ET.SubElement(tp, "Position")
        wp = ET.SubElement(pos, "WorldPosition")
        wp.attrib.update({"x": str(x), "y": str(y), "z": str(z), "h": "0"})
        if speed > 0:
            lact = ET.SubElement(ET.SubElement(pa, "PrivateAction"), "LongitudinalAction")
            lsp = ET.SubElement(lact, "SpeedAction")
            ET.SubElement(lsp, "SpeedActionDynamics").attrib.update(
                {"dynamicsShape": "step", "value": "0", "dynamicsDimension": "time"})
            tgt = ET.SubElement(lsp, "SpeedActionTarget")
            abs_ = ET.SubElement(tgt, "AbsoluteTargetSpeed")
            abs_.set("value", str(speed))

    _init_action("ego", *config.get("ego_spawn", (0, 0, 0)), speed=config.get("ego_speed", 10))
    for i, npc in enumerate(config.get("npcs", [])):
        _init_action(f"npc_{i}", *npc.get("spawn", (0, 0, 0)), speed=npc.get("speed", 8))
    for i, ped in enumerate(config.get("pedestrians", [])):
        _init_action(f"pedestrian_{i}", *ped.get("spawn", (0, 0, 0)), speed=ped.get("speed", 1.4))

    # Story / Act / end condition
    story = ET.SubElement(sb, "Story")
    story.set("name", "CarlaGUIStory")
    act = ET.SubElement(story, "Act")
    act.set("name", "CarlaGUIAct")
    ET.SubElement(act, "ManeuverGroup").set("name", "maneuverg")
    sc = ET.SubElement(act, "StartTrigger")
    cg = ET.SubElement(sc, "ConditionGroup")
    cond = ET.SubElement(cg, "Condition")
    cond.attrib.update({"name": "start", "delay": "0", "conditionEdge": "none"})
    by_val = ET.SubElement(cond, "ByValueCondition")
    sim_t = ET.SubElement(by_val, "SimulationTimeCondition")
    sim_t.attrib.update({"value": "0", "rule": "greaterThan"})

    end = ET.SubElement(sb, "StopTrigger")
    cg2 = ET.SubElement(end, "ConditionGroup")
    c2 = ET.SubElement(cg2, "Condition")
    c2.attrib.update({"name": "stop", "delay": "0", "conditionEdge": "none"})
    bv2 = ET.SubElement(c2, "ByValueCondition")
    st2 = ET.SubElement(bv2, "SimulationTimeCondition")
    st2.attrib.update({"value": str(config.get("stop_time", 30)), "rule": "greaterThan"})

    # Pretty print
    raw = ET.tostring(root, encoding="unicode")
    pretty = minidom.parseString(raw).toprettyxml(indent="  ")
    with open(path, "w") as f:
        f.write(pretty)


# ─────────────────────────────────────────────────────────────────────────────
# Python script exporter
# ─────────────────────────────────────────────────────────────────────────────
def export_python(config: dict, path: str):
    ego_sp = config.get("ego_spawn", (0, 0, 0))
    ego_dst = config.get("ego_dest", (10, 10, 0))
    ego_bp = config.get("ego_blueprint", "vehicle.tesla.model3")
    ego_speed = config.get("ego_speed", 10)
    stop_time = config.get("stop_time", 30)
    weather = config.get("weather_preset", "ClearNoon")
    npcs = config.get("npcs", [])
    peds = config.get("pedestrians", [])

    npc_lines = []
    for i, npc in enumerate(npcs):
        sp = npc.get("spawn", (0, 0, 0))
        spd = npc.get("speed", 8)
        bp = npc.get("blueprint", "vehicle.audi.a2")
        npc_lines.append(textwrap.dedent(f"""
        # NPC {i}
        npc_bp_{i} = bp_lib.find("{bp}")
        npc_sp_{i} = carla.Transform(carla.Location(x={sp[0]}, y={sp[1]}, z={sp[2]}))
        npc_{i} = world.try_spawn_actor(npc_bp_{i}, npc_sp_{i})
        if npc_{i}:
            actors.append(npc_{i})
            npc_{i}.set_autopilot(True)
            tm.vehicle_percentage_speed_difference(npc_{i}, {100 - int(spd * 10)})
        """).strip())

    ped_lines = []
    for i, ped in enumerate(peds):
        sp = ped.get("spawn", (0, 0, 0))
        spd = ped.get("speed", 1.4)
        ped_lines.append(textwrap.dedent(f"""
        # Pedestrian {i}
        ped_bp_{i} = random.choice(list(bp_lib.filter("walker.pedestrian.*")))
        ped_sp_{i} = carla.Transform(carla.Location(x={sp[0]}, y={sp[1]}, z={sp[2]}))
        ped_{i} = world.try_spawn_actor(ped_bp_{i}, ped_sp_{i})
        if ped_{i}:
            actors.append(ped_{i})
            ctrl_{i} = world.spawn_actor(controller_bp, carla.Transform(), attach_to=ped_{i})
            actors.append(ctrl_{i})
            world.tick()
            ctrl_{i}.start()
            ctrl_{i}.go_to_location(world.get_random_location_from_navigation())
            ctrl_{i}.set_max_speed({spd})
        """).strip())

    script = textwrap.dedent(f"""
    #!/usr/bin/env python3
    \"\"\"Auto-generated by CARLA GUI — scenario script.\"\"\"

    import carla, time, random

    HOST = "{config.get('host', 'localhost')}"
    PORT = {config.get('port', 2000)}
    STOP_TIME = {stop_time}  # seconds

    def main():
        client = carla.Client(HOST, PORT)
        client.set_timeout(10.0)
        world = client.get_world()
        tm = client.get_trafficmanager()
        bp_lib = world.get_blueprint_library()
        controller_bp = bp_lib.find("controller.ai.walker")
        actors = []

        try:
            # Weather
            world.set_weather(carla.WeatherParameters.{weather})

            # Ego vehicle
            ego_bp = bp_lib.find("{ego_bp}")
            if ego_bp.has_attribute("role_name"):
                ego_bp.set_attribute("role_name", "hero")
            ego_spawn = carla.Transform(carla.Location(x={ego_sp[0]}, y={ego_sp[1]}, z={ego_sp[2]}))
            ego = world.try_spawn_actor(ego_bp, ego_spawn)
            if ego:
                actors.append(ego)
                ego.set_autopilot(True)
                tm.set_desired_speed(ego, {ego_speed})
            else:
                print("[ERR] Ego vehicle spawn failed.")

            {"".join(npc_lines) or "# No NPCs configured"}

            {"".join(ped_lines) or "# No pedestrians configured"}

            print(f"[OK] Scenario running for {{STOP_TIME}}s ...")
            time.sleep(STOP_TIME)

        finally:
            print(f"[INFO] Cleaning up {{len(actors)}} actors ...")
            for a in actors:
                try: a.destroy()
                except Exception: pass
            print("[OK] Done.")

    if __name__ == "__main__":
        main()
    """).strip()

    with open(path, "w") as f:
        f.write(script)
